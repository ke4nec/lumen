bool glyphPixel(std::uint32_t codePoint, int gx, int gy) {
    if (gy < 0 || gy > 6) {
        return false;
    }
    if (codePoint < 32 || codePoint > 126) {
        // Placeholder box for non-ASCII (CJK/emoji) code points.
        return gx >= 0 && gx < 4 && gy >= 1 && gy < 6;
    }
    if (gx < 0 || gx > 4) {
        return false;
    }
    return (kFont5x7[codePoint - 32][gy] & (1U << (4 - gx))) != 0U;
}

std::uint32_t decodeCodePoint(const std::string& text, std::size_t& i) {
    const auto byte = static_cast<unsigned char>(text[i]);
    std::uint32_t cp = byte;
    std::size_t extra = 0;
    if ((byte & 0xE0U) == 0xC0U) {
        cp = byte & 0x1FU;
        extra = 1;
    } else if ((byte & 0xF0U) == 0xE0U) {
        cp = byte & 0x0FU;
        extra = 2;
    } else if ((byte & 0xF8U) == 0xF0U) {
        cp = byte & 0x07U;
        extra = 3;
    }
    for (std::size_t k = 0; k < extra && i + 1 < text.size(); ++k) {
        ++i;
        cp = (cp << 6U) | (static_cast<unsigned char>(text[i]) & 0x3FU);
    }
    ++i;
    return cp;
}

